def get_jti_by_text_name(text_name: str) -> str:
    """텍스트명으로 JTI 코드 조회"""
    text_lower = text_name.lower()
    
    # 긴 매칭부터 우선 (더 구체적인 매칭)
    sorted_mappings = sorted(TEXT_TO_JTI_MAPPINGS.items(), key=lambda x: len(x[0]), reverse=True)
    
    for name, jti_code in sorted_mappings:
        if name.lower() in text_lower:
            return jti_code
    
    return None

def get_text_name_by_jti(jti_code: str) -> str:
    """JTI 코드로 텍스트명 조회"""
    return JTI_CODE_MAPPINGS.get(jti_code, f"Unknown_{jti_code}")

def get_series_by_jti(jti_code: str) -> str:
    """JTI 코드로 시리즈명 조회"""
    for series_name, jti_codes in SERIES_GROUPS.items():
        if jti_code in jti_codes:
            return series_name
    return "Unknown_Series"

def list_all_processed_texts() -> list:
    """실제 처리된 모든 텍스트 목록 반환"""
    return list(JTI_CODE_MAPPINGS.keys())

def validate_jti_code(jti_code: str) -> bool:
    """JTI 코드 유효성 검증"""
    return jti_code in JTI_CODE_MAPPINGS

